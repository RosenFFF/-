type Axe = { violations: string[]; incompleteContrast: number; passes: number };

async function axeOf(page: Page): Promise<Axe> {
  const r = await new AxeBuilder({ page }).analyze();
  return {
    violations: r.violations.map((v) => v.id),
    incompleteContrast: r.incomplete
      .filter((i) => i.id === "color-contrast")
      .reduce((n, i) => n + i.nodes.length, 0),
    passes: r.passes.length,
  };
}

async function signIn(page: Page, role: keyof typeof ACCOUNTS) {
  await page.goto("/login");
  await page.locator('input[autocomplete="username"]').fill(ACCOUNTS[role].username);
  await page
    .locator('input[autocomplete="current-password"]')
    .fill(ACCOUNTS[role].password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.waitForURL((u) => !u.pathname.includes("/login"), { timeout: 30_000 });
}

test("demo-ready: upload → review → follow-up → audit on real backend", async ({
  page,
}, info) => {
  const size = info.project.name;
  await mkdir(output, { recursive: true });
  const timings: Record<string, number | null> = {};
  const pages: Record<string, unknown> = {};
  const shot = async (name: string, extra: Record<string, unknown> = {}) => {
    await expect(page.locator(".mock-banner")).toHaveCount(0);
    const axe = await axeOf(page);
    const overflow = await page.evaluate(
      () => document.documentElement.scrollWidth > window.innerWidth + 1,
    );
    const file = `${name}-${size}`;
    await page.screenshot({ path: resolve(output, `${file}.png`), fullPage: true });
    pages[name] = { axe, horizontalOverflow: overflow, ...extra };
    await writeFile(
      resolve(output, `${file}.json`),
      JSON.stringify(
        { environment: ENVIRONMENT, viewport: page.viewportSize(), page: name, axe, horizontalOverflow: overflow, ...extra, screenshot: `${file}.png` },
        null,
        2,
      ),
    );
  };

  // Test-only tap: copy the follow-up SSE body (Playwright cannot read streamed bodies).
  await page.addInitScript(() => {
    const orig = window.fetch.bind(window);
    (window as unknown as { __sse: string[] }).__sse = [];
    window.fetch = async (input, init) => {
      const res = await orig(input, init);
      const url = typeof input === "string" ? input : input instanceof URL ? input.href : input.url;
      if (/\/reviews\/[^/]+\/messages$/.test(new URL(url, location.href).pathname) && init?.method === "POST") {
        void res.clone().text().then((txt) => (window as unknown as { __sse: string[] }).__sse.push(txt));
      }
      return res;
    };
  });
  // Cold page load of /login (Navigation Timing from the browser, not estimated).
  await page.goto("/login");
  await page.waitForLoadState("load");
  const nav = await page.evaluate(() => {
    const n = performance.getEntriesByType("navigation")[0] as PerformanceNavigationTiming;
    return { dcl: n.domContentLoadedEventEnd, load: n.loadEventEnd };
  });
  timings.login_dom_content_loaded_ms = Math.round(nav.dcl);
  timings.login_load_ms = Math.round(nav.load);
  await shot("login");

  await signIn(page, "reviewer");
  await page.goto("/cases/new");
  await expect(page.getByRole("heading", { name: "上传单证" })).toBeVisible();
  await shot("upload");

  const pdf = await readFile(samplePdf);
  await page.locator('input[type="file"]').setInputFiles({
    name: "invoice.pdf",
    mimeType: "application/pdf",
    buffer: pdf,
  });
  let t0 = Date.now();
  await page.getByRole("button", { name: "开始识别", exact: true }).click();
  await page.waitForURL(/\/cases\/[^/]+\/extract/, { timeout: 180_000 });
  await expect(page.locator(".report-verification")).toBeVisible({ timeout: 120_000 });
  timings.upload_to_extract_ms = Date.now() - t0;
  const extractVerification = (await page.locator(".report-verification").innerText()).trim();
  await shot("extract", { verification: extractVerification });
  const docId = page.url().match(/cases\/([^/?#]+)/)![1];

  await page.goto(`/cases/${docId}/report`);
  t0 = Date.now();
  await page.getByRole("button", { name: "发起审查", exact: true }).click();
  const askLink = page.getByRole("link", { name: "继续追问", exact: true });
  await expect(askLink).toBeVisible({ timeout: 180_000 });
  timings.review_start_to_report_ms = Date.now() - t0;
  const reportVerification = (await page.locator(".report-verification").first().innerText()).trim();
  await shot("report", { verification: reportVerification });
  const reviewId = new URL((await askLink.getAttribute("href"))!, "https://x").searchParams.get("review");

  await askLink.click();
  const box = page.getByRole("textbox", { name: "例如：如何修改才能合规？" });
  await expect(box).toBeEnabled({ timeout: 30_000 });
  await box.fill("金额不一致应如何处理？");
  const respP = page.waitForResponse(
    (r) => /\/reviews\/[^/]+\/messages$/.test(new URL(r.url()).pathname) && r.request().method() === "POST",
    { timeout: 120_000 },
  );
  t0 = Date.now();
  await page.getByRole("button", { name: "发送", exact: true }).click();
  const resp = await respP;
  const askStatus = resp.status();
  const askContentType = resp.headers()["content-type"] ?? "";
  let askBody = "";
  await expect(page.locator(".error-notice")).toContainText(/模型暂不可用/, { timeout: 90_000 });
  timings.ask_send_to_error_ms = Date.now() - t0;
  await expect(page.locator(".chat-message.assistant")).toHaveCount(0);
  await expect
    .poll(() => page.evaluate(() => (window as unknown as { __sse: string[] }).__sse.length))
    .toBeGreaterThan(0);
  askBody = (await page.evaluate(() => (window as unknown as { __sse: string[] }).__sse.join("\n"))).slice(0, 1200);
  expect(askBody).not.toBe("");
  const askCode = /"code"\s*:\s*"([A-Z_]+)"/.exec(askBody)?.[1] ?? null;
  const askProblemStatus = Number(/"status"\s*:\s*(\d{3})/.exec(askBody)?.[1] ?? 0) || null;
  const askEvents = [...askBody.matchAll(/^event: (\w+)/gm)].map((m) => m[1]);
  // HTTP 200 alone is never success: the stream must carry only `error` with Problem 503.
  if (askStatus === 200) {
    expect(askContentType).toContain("text/event-stream");
    {
      expect(askEvents).toEqual(["error"]);
      expect(askCode).toBe("MODEL_UNAVAILABLE");
      expect(askProblemStatus).toBe(503);
    }
  } else {
    expect(askStatus).toBe(503);
  }
  await shot("ask", {
    askHttpStatus: askStatus,
    askContentType,
    askSseEvents: askEvents,
    askProblemStatus,
    askProblemCode: askCode,
    assistantMessages: 0,
  });

  await page.getByRole("button", { name: "退出", exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await signIn(page, "admin");
  t0 = Date.now();
  await page.goto("/audit");
  await page.getByRole("button", { name: "全局看板", exact: true }).click();
  await expect(page.locator(".audit-stats, [data-testid=audit-stats], table").first()).toBeVisible({ timeout: 30_000 });
  timings.audit_open_to_stats_ms = Date.now() - t0;
  await shot("audit-admin");

  t0 = Date.now();
  const modelsResp = page.waitForResponse((r) => r.url().endsWith("/api/v1/system/models"));
  await page.goto("/system/models");
  const mr = await modelsResp;
  const modelsRaw = await mr.text();
  // (b) ACTUAL probe: raw backend response captured during this run + live Ollama reachability.
  const ollamaUrl = process.env.FIXTURE_OLLAMA_URL ?? "http://127.0.0.1:11434";
  let ollama: { url: string; reachable: boolean; status?: number; models?: string[]; error?: string };
  try {
    const r = await fetch(`${ollamaUrl}/api/tags`, { signal: AbortSignal.timeout(3000) });
    const j = (await r.json()) as { models?: { name: string }[] };
    ollama = { url: ollamaUrl, reachable: true, status: r.status, models: (j.models ?? []).map((m) => m.name) };
  } catch (e) {
    ollama = { url: ollamaUrl, reachable: false, error: String(e).slice(0, 200) };
  }
  const probeFile = `models-probe-${size}.json`;
  await writeFile(
    resolve(output, probeFile),
    JSON.stringify(
      {
        evidence_kind: "actual_probe",
        note: "Raw GET /api/v1/system/models from the fixture backend during this run (no credentials in body) plus a live Ollama /api/tags probe.",
        label: ENVIRONMENT.label,
        capturedAt: new Date().toISOString(),
        http_status: mr.status(),
        system_models_raw: JSON.parse(modelsRaw) as unknown,
        ollama_probe: ollama,
      },
      null,
      2,
    ),
  );
  const models = JSON.parse(modelsRaw) as {
    degrade_level: string;
    llm_provider_chain?: string[];
    models: { category: string; provider: string; model: string; healthy: boolean }[];
  };
  await expect(page.getByTestId("models-level")).toContainText(models.degrade_level);
  timings.models_page_ms = Date.now() - t0;
  const anyLlm = models.models.some((m) => m.category === "llm" && m.healthy);
  if (!anyLlm) await expect(page.getByTestId("models-no-llm")).toBeVisible();
  await shot("models", {
    modelsWire: {
      degrade_level: models.degrade_level,
      llm_provider_chain: models.llm_provider_chain,
      models: models.models.map((m) => ({ category: m.category, provider: m.provider, model: m.model, healthy: m.healthy })),
    },
    noLlmBannerShown: !anyLlm,
  });

  for (const [name, v] of Object.entries(pages) as [string, { axe: Axe; horizontalOverflow: boolean }][]) {
    expect(v.axe.violations, `${name} axe`).toEqual([]);
    expect(v.axe.incompleteContrast, `${name} incomplete contrast`).toBe(0);
    expect(v.horizontalOverflow, `${name} overflow`).toBe(false);
  }
  await writeFile(
    resolve(output, `run-${size}.json`),
    JSON.stringify(
      {
        environment: ENVIRONMENT,
        evidence: {
          contract_assertion: "hardcoded: UI shows no-LLM banner / L3 when wire says so; ollama models=[] is an expectation, not a probe",
          actual_probe: probeFile,
          actual_degrade_level: models.degrade_level,
          actual_ollama_reachable: ollama.reachable,
          actual_ollama_models: ollama.models ?? null,
        },
        viewport: size,
        documentId: docId,
        reviewId,
        timings,
        pages,
        measuredAt: new Date().toISOString() },
      null,
      2,
    ),
  );
});
